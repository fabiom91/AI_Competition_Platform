/* Offline shim for the static demo.
 *
 * The demo is a copy of the platform's own frontend. Rather than rewrite 2,700 lines of
 * application JavaScript, this file removes the two things that reach the outside world,
 * so that the copied main.js / dashboard.js / read_article.js run unmodified:
 *
 *   1. Firebase. The real pages load the Firebase SDK and firebaseui from gstatic and
 *      initialise an app from a config file that is not in this repository. The demo pages
 *      load this file instead, which defines a `firebase` global that resolves to "nobody
 *      is signed in" and never opens a connection. Nothing here talks to Google.
 *
 *   2. The server. Every data call in the frontend is a jQuery $.post to a Flask endpoint
 *      that reads Firestore. Those are intercepted below and answered from DEMO_DATA
 *      (demo-data.js, generated by build_demo.py). No HTTP request leaves the page.
 *
 * Anything that would write — joining a competition, submitting, commenting, voting —
 * resolves to a refusal, and the sign-in controls are hidden, because there is nothing
 * behind them.
 *
 * Load order matters: jQuery, then this file, then demo-data.js, then the application JS.
 */

(function () {
  "use strict";

  // ---------------------------------------------------------------- Firebase stand-in

  function noop() {}

  function thenable(value) {
    // Enough of a promise for the copied code, which only chains .then/.catch.
    var p = {
      then: function (fn) { if (fn) { try { fn(value); } catch (e) {} } return p; },
      catch: function () { return p; }
    };
    return p;
  }

  var authInstance = {
    currentUser: null,
    onAuthStateChanged: function (cb) { if (cb) { cb(null); } },
    signOut: function () { return thenable(); },
    signInWithEmailAndPassword: function () { return thenable(null); },
    createUserWithEmailAndPassword: function () { return thenable(null); },
    sendPasswordResetEmail: function () { return thenable(); },
    setPersistence: function () { return thenable(); }
  };

  function GoogleAuthProvider() { this.providerId = "google.com"; }
  GoogleAuthProvider.PROVIDER_ID = "google.com";

  var authFn = function () { return authInstance; };
  authFn.GoogleAuthProvider = GoogleAuthProvider;
  authFn.Auth = { Persistence: { LOCAL: "local", SESSION: "session", NONE: "none" } };

  window.firebase = {
    initializeApp: noop,
    analytics: noop,
    auth: authFn,
    firestore: function () { return {}; },
    storage: function () { return {}; }
  };

  window.firebaseui = {
    auth: {
      AuthUI: function () { this.start = noop; this.reset = noop; },
      CredentialHelper: { NONE: "none" }
    }
  };

  // ------------------------------------------------------------------ Offline $.post

  var REFUSAL = {
    error: "demo",
    message: "This is a static demo: there is no database behind it."
  };

  function parse(value) {
    if (typeof value !== "string") { return value; }
    try { return JSON.parse(value); } catch (e) { return value; }
  }

  function answer(url, payload) {
    var data = window.DEMO_DATA || {};
    payload = payload || {};

    switch (url) {
      case "/get_all_articles":
      case "/get_all_articles_lists":
        return data.articles || [];

      case "/get_full_article":
        return data.full_article || {};

      case "/get_article":
        return (data.full_article && data.full_article.main) || {};

      case "/get_author_profile":
        return data.author || {};

      case "/check_additional_resources":
        return data.resources || {};

      case "/get_article_download":
        return data.article_download || [""];

      case "/load_search_archive":
        return data.search_archive || [];

      case "/get_user":
      case "/get_all_users":
        return null;

      case "/is_user_joined":
        return false;

      // Fire-and-forget on the real site; nothing to do here.
      case "/update_leaderscore":
      case "/remove_downloaded_zip":
        return null;

      default:
        // Everything else writes. Refuse rather than pretend it worked.
        if (window.console && console.info) {
          console.info("[demo] " + url + " is not available in the static demo.");
        }
        return REFUSAL;
    }
  }

  function deferredFor(url, payload) {
    var d = window.jQuery.Deferred();
    // Asynchronous, like the real call, so callers that rely on .done() firing after the
    // current tick behave the same.
    window.setTimeout(function () { d.resolve(answer(url, parse(payload))); }, 0);
    return d.promise();
  }

  if (window.jQuery) {
    window.jQuery.post = function (url, data) { return deferredFor(url, data); };
    window.jQuery.get = function (url, data) { return deferredFor(url, data); };
    window.jQuery.ajax = function (options) {
      options = options || {};
      var d = deferredFor(options.url, options.data);
      if (typeof options.success === "function") { d.done(options.success); }
      return d;
    };
  }

  // ------------------------------------------- Guards for libraries that stay remote
  // jQuery and Bootstrap are served from the copies this repository already vendors.
  // Font Awesome, Google Fonts, jQuery UI and bootbox are still loaded from their CDNs
  // and are cosmetic or unreachable here; stub the two that are called, so that a blocked
  // or offline CDN degrades the look rather than stopping the page.
  if (window.jQuery && window.jQuery.fn && !window.jQuery.fn.autocomplete) {
    window.jQuery.fn.autocomplete = function () { return this; };
  }
  if (!window.bootbox) {
    window.bootbox = { dialog: noop, alert: noop, confirm: noop, prompt: noop };
  }

  // --------------------------------------------------------------- Demo-only chrome

  function markAsDemo() {
    var doc = window.document;

    // No sign-in: there is no authentication behind it.
    ["log_reg_list", "login_button", "register_button", "create_article_btn"].forEach(
      function (id) {
        var el = doc.getElementById(id);
        if (el) { el.style.display = "none"; }
      }
    );

    if (window.self !== window.top) { return; }   // banner on the outer page only

    var banner = doc.createElement("div");
    banner.setAttribute("id", "demo_banner");
    banner.style.cssText =
      "background:#502a70;color:#fff;padding:8px 16px;font-size:90%;" +
      "font-family:Lato,sans-serif;line-height:1.4;";
    banner.innerHTML =
      "<strong>Static demo.</strong> A copy of the platform's frontend with the Firebase " +
      "and server calls removed. One competition is shown, frozen as it was published; " +
      "sign-in, submission and commenting do nothing because there is no database behind " +
      "this page. The leaderboard was recomputed from the submission files in " +
      "<code>data/</code> — see <a style='color:#fff;text-decoration:underline' " +
      "href='README.md'>README.md</a>.";
    if (doc.body) { doc.body.insertBefore(banner, doc.body.firstChild); }
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", markAsDemo);
  } else {
    markAsDemo();
  }
})();
